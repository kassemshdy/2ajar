// Generates src/schema.d.ts from the FastAPI OpenAPI document (no running server needed).
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const apiDir = resolve(here, "../../../apps/api");
const python = process.env.API_PYTHON ?? resolve(apiDir, ".venv/bin/python");

const json = execFileSync(
  python,
  ["-c", "import json; from app.main import create_app; print(json.dumps(create_app().openapi(), sort_keys=True))"],
  { cwd: apiDir, env: { ...process.env, LOG_LEVEL: "WARNING" }, encoding: "utf8" },
);
const spec = JSON.parse(json);
mkdirSync(resolve(here, "../openapi"), { recursive: true });
writeFileSync(resolve(here, "../openapi/openapi.json"), JSON.stringify(spec, null, 2) + "\n");
const ast = await openapiTS(spec);
const header = "// AUTO-GENERATED by packages/contracts/scripts/gen.mjs — do not edit.\n";
writeFileSync(resolve(here, "../src/schema.d.ts"), header + astToString(ast));
console.log("contracts: wrote openapi/openapi.json and src/schema.d.ts");
